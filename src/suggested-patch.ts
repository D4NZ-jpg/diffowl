export const SUGGESTED_PATCH_MAX_LINES = 20;
export const SUGGESTED_PATCH_MAX_BYTES = 16 * 1024;
export const SUGGESTED_PATCH_SECURITY = {
  network: "denied",
  secrets: "denied",
  memoryBytes: 1024 * 1024 * 1024,
  cpuCount: 2,
  processLimit: 128,
  temporaryBytes: 64 * 1024 * 1024,
  workspace: "read_only",
} as const;

export interface SuggestedPatchProposal {
  startLine: number;
  endLine: number;
  replacement: string;
}

export interface SuggestedPatchValidation {
  commandIndex: number;
  commandHash: string;
  status: "passed";
}

export interface SuggestedPatch {
  id: string;
  path: string;
  startLine: number;
  endLine: number;
  replacement: string;
  reviewedHeadSha: string;
  sourceHash: string;
  validation: SuggestedPatchValidation;
}

export interface SuggestedPatchValidationRequest {
  repository: string;
  headSha: string;
  path: string;
  startLine: number;
  endLine: number;
  expected: string;
  replacement: string;
  sandboxImage: string;
  command: ValidationCommand & { commandIndex: number };
  security: typeof SUGGESTED_PATCH_SECURITY;
  signal: AbortSignal;
}

export type SuggestedPatchValidationResult = {
  status: "passed" | "failed" | "timed_out" | "aborted" | "stale" | "unavailable" | "error";
  exitCode?: number | undefined;
  stdout: string;
  stderr: string;
  truncated: boolean;
  limitation?: string | undefined;
};

function hash(value: string): string {
  return `sha256:${createHash("sha256").update(value).digest("hex")}`;
}

function lineCount(value: string): number {
  return value.length === 0 ? 0 : value.split("\n").length;
}

function sourceLines(value: string): string[] | undefined {
  if (
    value.includes("\0") ||
    value.includes("�") ||
    /(?:@generated|auto[- ]generated|code generated.{0,120}do not edit|generated by)/iu.test(
      value.slice(0, 8 * 1024),
    )
  ) {
    return undefined;
  }
  const normalized = value.replaceAll("\r\n", "\n");
  const lines = normalized.split("\n");
  if (lines.at(-1) === "") lines.pop();
  return lines;
}

